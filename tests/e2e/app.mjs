// End-to-end check of the built app in real Chrome, phone-sized.
import { chromium } from 'playwright-core';
const URL_ = 'http://127.0.0.1:4173/?models=http://127.0.0.1:8099/kokoro';
const shot = (p, n) => p.screenshot({ path: `tests/e2e/shots/${n}.png` });
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: 'light' });
const p = await ctx.newPage();
const logs = [];
p.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`${m.type()}: ${m.text()}`); });
p.on('pageerror', (e) => logs.push(`pageerror: ${e.message}`));
await p.goto(URL_); await p.waitForSelector('.empty');
await shot(p, '01-library-empty');
await p.setInputFiles('input[type=file]', ['tests/fixtures/pdf-20pages.pdf', 'tests/fixtures/book.epub']);
await p.waitForSelector('.book', { timeout: 60000 });
await p.waitForFunction(() => document.querySelectorAll('.book').length === 2, null, { timeout: 60000 });
await shot(p, '02-library');
console.log('books:', await p.$$eval('.book h3', (e) => e.map((x) => x.textContent)));
console.log('notices:', await p.$$eval('.notice', (e) => e.map((x) => x.textContent)));
await p.click('.book >> nth=0'); await p.waitForSelector('.prose .s');
await shot(p, '03-reader');
await p.click('.tabs button:nth-child(3)');
await p.waitForSelector('.play');
await shot(p, '04-player');
await p.click('.play');
const t0 = Date.now();
await p.waitForFunction(() => window.__app.narrator?.state === 'playing', null, { timeout: 240000 });
console.log('time to first audio (incl. voice load) ms:', Date.now() - t0);
await p.waitForTimeout(12000);
const info = await p.evaluate(() => ({ idx: window.__app.narrator.idx, st: window.__app.narrator.state, ctx: window.__app.player.ctx.currentTime, queued: window.__app.player.queuedSeconds }));
console.log('after 12s:', info);
await shot(p, '05-player-playing');
await p.click('.tabs button:nth-child(2)'); await p.waitForSelector('.s.now'); await shot(p, '06-reader-follow');
await p.click('.tabs button:nth-child(4)'); await p.waitForSelector('.sec'); await shot(p, '07-settings');
console.log('console issues:', logs.slice(0, 12));
await b.close();
